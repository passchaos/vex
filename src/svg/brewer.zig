pub const palette_count = palettes.len;
pub const color_count: usize = count: {
    var total: usize = 0;
    for (palettes) |palette| total += palette.colors.len / 7;
    break :count total;
};

pub fn find(scheme: []const u8, raw_index: []const u8) ?[]const u8 {
    const index = std.fmt.parseInt(usize, raw_index, 10) catch return null;
    var low: usize = 0;
    var high: usize = palettes.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        switch (std.ascii.orderIgnoreCase(scheme, palettes[mid].name)) {
            .lt => high = mid,
            .gt => low = mid + 1,
            .eq => {
                if (index == 0) return null;
                const start = (index - 1) * 7;
                if (start + 7 > palettes[mid].colors.len) return null;
                return palettes[mid].colors[start .. start + 7];
            },
        }
    }
    return null;
}

test "complete Graphviz ColorBrewer table is indexed" {
    try std.testing.expectEqual(@as(usize, 265), palette_count);
    try std.testing.expectEqual(@as(usize, 1689), color_count);
    try std.testing.expectEqualStrings("#f7fbff", find("blues9", "1").?);
    try std.testing.expectEqualStrings("#f7f7f7", find("rdbu9", "5").?);
    try std.testing.expectEqualStrings("#ffed6f", find("set312", "12").?);
    try std.testing.expectEqualStrings("#00441b", find("BuGn9", "9").?);
    try std.testing.expect(find("blues9", "0") == null);
    try std.testing.expect(find("blues9", "10") == null);
    try std.testing.expect(find("unknown9", "1") == null);
}
